// Analyze Payment Screenshot with dual-score explanation
export async function analyzePaymentScreenshot({
  imageSrc,
  imageName,
  groqApiKey,
  geminiApiKey,
  customNotes = ''
}) {
  // If user provided Gemini API Key
  if (geminiApiKey) {
    try {
      const result = await callGeminiVision(imageSrc, geminiApiKey, customNotes);
      if (result) return result;
    } catch (e) {
      console.warn('Gemini vision API error, falling back to local inspection:', e);
    }
  }

  // If user provided Groq API Key
  if (groqApiKey) {
    try {
      const result = await callGroqVision(imageSrc, groqApiKey, customNotes);
      if (result) return result;
    } catch (e) {
      console.warn('Groq vision API error, falling back to local inspection:', e);
    }
  }

  // Robust Local On-Device AI Heuristic Engine (Gemma 2B simulated rules)
  return runLocalScreenshotForensics(imageSrc, imageName, customNotes);
}

