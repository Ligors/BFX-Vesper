// Analyze SMS or Fake OTP message
export async function analyzeSmsMessage({
  messageText,
  senderHeader = '',
  groqApiKey,
  geminiApiKey
}) {
  const text = (messageText || '').trim();
  const header = (senderHeader || '').trim().toUpperCase();

  // Keyword flags
  const urgentWords = ['immediately', 'within 24 hours', 'blocked', 'suspended', 'disconnected', 'tonight', 'deactivated', 'kyc update', 'penalty', 'urgent', 'electricity will be cut'];
  const otpWords = ['otp', 'one time password', 'secret pin', 'do not share', 'verification code'];
  const linkWords = ['bit.ly', '.apk', 'tinyurl', 'ngrok', 'http://', 'https://', '.top', '.xyz', '.site', 'download'];
  const bankWords = ['sbi', 'hdfc', 'icici', 'axis', 'punjab national', 'bank', 'yono', 'electricity'];

  let matchedUrgent = urgentWords.filter(w => text.toLowerCase().includes(w));
  let matchedOtp = otpWords.filter(w => text.toLowerCase().includes(w));
  let matchedLinks = linkWords.filter(w => text.toLowerCase().includes(w));
  let matchedBanks = bankWords.filter(w => text.toLowerCase().includes(w));

  // Sender Header check
  const isPersonalNumber = /^(\+91|91)?[6-9]\d{9}$/.test(header.replace(/[\s-]/g, ''));
  const isTraiFormatted = /^[A-Z]{2}-[A-Z0-9]{6}$/i.test(header) || /^[A-Z]{2}[A-Z0-9]{6}$/i.test(header);

  let score = 10; // baseline
  let whyScam = [];
  let whySafe = [];

  // Urgent threats
  if (matchedUrgent.length > 0) {
    score += 35;
    whyScam.push(`Urgency & Threat Traps (${matchedUrgent.length * 15}%): Found high-pressure phrases like "${matchedUrgent.slice(0, 3).join(', ')}". Scammers deliberately create panic to make elders act without thinking.`);
  }

  // Suspicious Links or APK files
  if (text.includes('.apk') || matchedLinks.length > 0) {
    score += 30;
    if (text.includes('.apk')) {
      whyScam.push('Malicious APK Android App Link (30%): The message invites you to install an unknown application (.apk). This is a known Trojan that can steal OTPs and bank credentials silently.');
    } else {
      whyScam.push(`Suspicious External Link: Contains unverified web links (${matchedLinks.join(', ')}) instead of official banking web domains.`);
    }
  }

  // Personal Phone Number claiming to be bank / government
  if (isPersonalNumber && (matchedBanks.length > 0 || matchedUrgent.length > 0)) {
    score += 25;
    whyScam.push('Fake Sender Header: Sent from a private 10-digit mobile number instead of an authorized Indian TRAI 6-character bank ID (like AD-SBIINB or VM-HDFCBK). No bank in India sends official warnings from a personal mobile!');
  }

  // OTP demand
  if (matchedOtp.length > 0 && text.toLowerCase().includes('share')) {
    score += 25;
    whyScam.push('Direct OTP Exfiltration Attempt: Message asks to share or forward an OTP. Genuine banks NEVER ask you to disclose an OTP to anyone.');
  }

  // Cap score at 99
  score = Math.min(Math.max(score, 5), 98);

  // If score is safe (e.g. genuine bank debit alert)
  if (score < 30) {
    return {
      scamScore: score,
      status: 'SAFE',
      senderType: isTraiFormatted ? 'Registered TRAI Telecom Header' : 'Unknown',
      whyScam: [
        `Minor Risk (${score}%): Standard automated message format; caution is always recommended when clicking unfamiliar links.`
      ],
      whySafe: [
        `Safe Factor 1 (${100 - score}%): Uses transactional language without coercive threats or artificial deadlines.`,
        'Safe Factor 2: Does not request confidential PIN, OTP, password, or APK installation.',
        'Safe Factor 3: Contains standard Indian banking masked account format (e.g., A/C ending in XX1234).'
      ],
      seniorAdvice: 'This message appears to be a normal bank or service notification. Never forward any OTP contained in this message to anyone over phone or WhatsApp.'
    };
  }

  // Calculate safe percentage
  const safePercent = 100 - score;
  whySafe.push(`Unflagged Traits (${safePercent}%): Standard SMS network delivery structure without hidden binary payload.`);
  whySafe.push('Our system leaves this margin because raw carrier telemetry and registered SIM identity cannot be verified without telecom operator access.');

  return {
    scamScore: score,
    status: score >= 65 ? 'CRITICAL SCAM' : 'SUSPICIOUS WARNING',
    senderType: isPersonalNumber ? 'Personal Mobile (Impersonation)' : (isTraiFormatted ? 'Spoofed/Unregistered Header' : 'Unknown'),
    whyScam,
    whySafe,
    seniorAdvice: '🚨 DO NOT CLICK ANY LINK. DO NOT CALL ANY NUMBER IN THIS MESSAGE. DO NOT SHARE ANY OTP. Delete this message or show it to your family guardian.'
  };
}

// Optional Groq Vision API helper
async function callGroqVision(imageSrc, apiKey, notes) {
  // Can be called when user supplies their Groq API Key
  const prompt = `You are CyberSentinel, an AI specialized in Indian online fraud detection for senior citizens.
Analyze this payment screenshot for fake mod APKs (Fake PhonePe, Fake GPay, Fake Paytm).
Return a JSON object with:
- scamScore: integer 0-100
- status: "SAFE" or "SCAM"
- whyScam: array of reasons why it was scored as scam
- whySafe: array of reasons why remaining percentage was safe or unverified
- seniorAdvice: simple clear advice for an elderly person.`;

  const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      model: 'llama-3.2-11b-vision-preview',
      messages: [
        {
          role: 'user',
          content: [
            { type: 'text', text: prompt },
            { type: 'image_url', image_url: { url: imageSrc } }
          ]
        }
      ],
      temperature: 0.2
    })
  });

  const data = await response.json();
  const content = data.choices?.[0]?.message?.content;
  if (content) {
    try {
      const parsed = JSON.parse(content.replace(/```json|```/g, '').trim());
      return parsed;
    } catch {
      // fallback
    }
  }
  return null;
}

// Optional Gemini Vision API helper
async function callGeminiVision(imageSrc, apiKey, notes) {
  const cleanBase64 = imageSrc.replace(/^data:image\/[a-z]+;base64,/, '');
  const prompt = `You are CyberSentinel, an Indian Senior Citizen Anti-Scam Shield AI.
Analyze this payment receipt screenshot. Detect if this is an authentic UPI transaction or a fake screenshot generated by a mod APK (like Fake PhonePe, Spoof Paytm).
Check:
1. 12-digit Indian NPCI UTR reference number validity.
2. Font consistency on Rupee amount.
3. Status bar timestamp vs receipt timestamp.
Return strict JSON with fields: scamScore (0-100), status ("SAFE" or "SCAM"), amount, utrFound, whyScam (array of reasons for score), whySafe (array of reasons for remaining % not being scam), seniorAdvice.`;

  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{
        parts: [
          { text: prompt },
          { inline_data: { mime_type: 'image/jpeg', data: cleanBase64 } }
        ]
      }]
    })
  });

  const data = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (text) {
    try {
      const parsed = JSON.parse(text.replace(/```json|```/g, '').trim());
      return parsed;
    } catch {
      // fallback
    }
  }
  return null;
}
