// Payment screenshot analysis: Vision AI (Gemini / Groq) + OCR fallback + rule checks
import { ask, systemPrompt, normaliseResult, LANG_NAMES } from './ai.js';
import { checkPaymentFields, scoreFrom } from '../public/js/engine.js';

let workerP = null;
async function ocr(buffer) {
  try {
    const { createWorker } = await import('tesseract.js');
    workerP ||= createWorker('eng');
    const w = await workerP;
    const { data } = await w.recognize(buffer);
    return data.text || '';
  } catch (_e) {
    return '';
  }
}

const MONTHS = { jan: 0, feb: 1, mar: 2, apr: 3, may: 4, jun: 5, jul: 6, aug: 7, sep: 8, oct: 9, nov: 10, dec: 11 };
function parseDate(text) {
  let m = text.match(/(\d{1,2})\s*(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*,?\s*(\d{4})?[,\s]*(?:at\s*)?(\d{1,2}):(\d{2})\s*(am|pm)?/i);
  if (m) {
    let h = +m[4]; if (m[6]) { const pm = /pm/i.test(m[6]); if (pm && h < 12) h += 12; if (!pm && h === 12) h = 0; }
    const d = new Date(m[3] ? +m[3] : new Date().getFullYear(), MONTHS[m[2].toLowerCase().slice(0, 3)], +m[1], h, +m[5]);
    return toLocalIso(d);
  }
  m = text.match(/(\d{1,2})[\/-](\d{1,2})[\/-](\d{2,4})[,\s]+(\d{1,2}):(\d{2})(?::\d{2})?\s*(am|pm)?/i);
  if (m) {
    let h = +m[4]; if (m[6]) { const pm = /pm/i.test(m[6]); if (pm && h < 12) h += 12; if (!pm && h === 12) h = 0; }
    const y = m[3].length === 2 ? 2000 + +m[3] : +m[3];
    return toLocalIso(new Date(y, +m[2] - 1, +m[1], h, +m[5]));
  }
  return '';
}
const toLocalIso = (d) => isNaN(d) ? '' : `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}T${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}:00`;

export function extractFieldsFromText(text) {
  const t = text.replace(/[|]/g, ' ');
  const app = /phonepe/i.test(t) ? 'PhonePe' : /google pay|g pay|gpay/i.test(t) ? 'Google Pay' : /paytm/i.test(t) ? 'Paytm' : /bhim/i.test(t) ? 'BHIM' : '';
  const amt = t.match(/(?:₹|rs\.?|inr|z|%)\s?([\d,]+(?:\.\d{1,2})?)/i);
  const utr = t.match(/(?:utr|upi ref(?:erence)?(?: no\.?| number)?|ref(?:erence)? no\.?|upi transaction id|rrn)[:\s#.]*([0-9 ]{4,20})/i);
  const anyUtr = t.match(/\b(\d{12})\b/);
  const txn = t.match(/\b(T\d{18,24})\b/);
  const upis = [...t.matchAll(/\b([a-z0-9.\-_]{2,})@([a-z]{2,})\b/gi)].map((m) => m[0]);
  const status = (t.match(/(payment successful|transaction successful|paid successfully|completed|successful|failed|pending|processing)/i) || [])[0] || '';
  return {
    app, amount: amt ? amt[1].replace(/,/g, '') : '', utr: utr ? utr[1].replace(/\s/g, '') : anyUtr ? anyUtr[1] : '',
    txnId: txn ? txn[1] : '', datetime: parseDate(t), status, payeeUpi: upis[0] || '', payerUpi: upis[1] || '',
  };
}

