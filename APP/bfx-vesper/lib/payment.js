export async function analyzePayment({ buffer, mime, lang = 'en', expectedAmount = '', customKey = '', customProvider = '' }) {
  const nowIso = toLocalIso(new Date(Date.now() + (330 + new Date().getTimezoneOffset()) * 60000));
  let ai = null, aiError = null, fields = {}, ocrText = '';
  const bufStr = buffer ? buffer.toString('utf8', 0, Math.min(buffer.length, 300)) : '';
  const isSvg = (mime && mime.includes('svg')) || bufStr.includes('<svg');

  if (isSvg) {
    ocrText = buffer.toString('utf8');
    fields = extractFieldsFromText(ocrText);
  } else {
    try {
      const r = await ask({
        system: systemPrompt(lang),
        user: PAYMENT_PROMPT(lang, expectedAmount, nowIso),
        image: { mime: mime || 'image/png', b64: buffer.toString('base64') },
        customKey, customProvider,
      });
      ai = { ...normaliseResult(r.data), provider: r.provider, model: r.model, visual_flags: r.data.visual_flags || [], is_payment: r.data.is_payment_screenshot !== false };
      fields = r.data.fields || {};
    } catch (e) { aiError = e.noKeys ? 'NO_KEYS' : e.message; }

    if (!fields || (!fields.utr && !fields.amount)) {
      try {
        ocrText = await ocr(buffer);
        if (ocrText) {
          const f2 = extractFieldsFromText(ocrText);
          fields = { ...f2, ...Object.fromEntries(Object.entries(fields || {}).filter(([, v]) => v)) };
        }
      } catch (e) { aiError = (aiError ? aiError + ' | ' : '') + 'OCR: ' + e.message; fields ||= {}; }
    }
  }

  // If fields were extracted but vision AI was not available or SVG was used, check with text AI model
  if (!ai && (fields.amount || fields.utr || fields.app)) {
    try {
      const textSummary = `Payment screenshot forensic data: App=${fields.app || 'Unknown'}, Amount=₹${fields.amount || '0'}, UTR=${fields.utr || 'None'}, Status=${fields.status || 'Unknown'}. Expected amount: ₹${expectedAmount || 'None'}.`;
      const r = await ask({
        system: systemPrompt(lang),
        user: `Check this Indian payment receipt and verify if it is authentic or a spoofed mod APK:\n${textSummary}`,
        customKey, customProvider,
      });
      ai = { ...normaliseResult(r.data), provider: r.provider, model: r.model, visual_flags: [], is_payment: true };
    } catch (_e) { /* fall back safely to rule engine */ }
  }

  // Clean UPI handles from descriptive text
  if (fields) {
    if (fields.payeeUpi) {
      const m = String(fields.payeeUpi).match(/([a-zA-Z0-9.\-_]+@[a-zA-Z0-9]+)/);
      if (m) fields.payeeUpi = m[1];
    }
    if (fields.payerUpi) {
      const m = String(fields.payerUpi).match(/([a-zA-Z0-9.\-_]+@[a-zA-Z0-9]+)/);
      if (m) fields.payerUpi = m[1];
    }
  }

  const rules = checkPaymentFields(fields, { expectedAmount, now: nowIso });
  const ruleScore = scoreFrom(rules.signals, rules.safe);

  // If AI verified it as genuine and rule engine found no red flags, keep it strictly safe
  let finalScore = ai ? Math.round(ai.score * 0.6 + ruleScore * 0.4) : Math.max(ruleScore, 15);
  if (ai && ai.verdict === 'LOOKS_SAFE' && rules.signals.length === 0) {
    finalScore = Math.min(finalScore, 20);
  } else if (rules.signals.some((s) => s.code === 'UTR_FORMAT' || s.code === 'UTR_PATTERN' || s.code === 'AMOUNT_MISMATCH')) {
    finalScore = Math.max(finalScore, 75);
  }

  return {
    score: finalScore,
    verdict: finalScore >= 70 ? 'SCAM' : finalScore >= 40 ? 'SUSPICIOUS' : 'LOOKS_SAFE',
    fields, rules, ruleScore, ai, aiError, ocrUsed: !!ocrText,
  };
}
